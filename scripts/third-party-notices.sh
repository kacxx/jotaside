#!/usr/bin/env bash
# Writes THIRD_PARTY_NOTICES: the license texts of everything compiled into the
# release binaries, which the release archives ship next to LICENSE. MIT and
# BSD licenses require their notice in binary distributions too.
#
# Covers the Go standard library and every module linked into any of the six
# release builds (.goreleaser.yaml), and copies every license-like file in each
# module's root, not just LICENSE: modernc.org/libc, for one, keeps the musl
# and Go notices it carries in LICENSE-3RD-PARTY.md. go-licenses reports only
# the main file and leaves out the standard library.
#
#   scripts/third-party-notices.sh          # rewrite THIRD_PARTY_NOTICES
#   scripts/third-party-notices.sh --check  # fail if it is out of date (CI)
set -euo pipefail

cd "$(dirname "$0")/.."
OUT=THIRD_PARTY_NOTICES
MAIN="$(go list -m)"

go mod download

# path@version of every non-standard module linked into a release build.
modules() {
  for os in linux darwin windows; do
    for arch in amd64 arm64; do
      GOOS=$os GOARCH=$arch CGO_ENABLED=0 go list -deps \
        -f '{{with .Module}}{{.Path}}@{{.Version}}{{end}}' ./cmd/jotaside
    done
  done | grep -v "^$MAIN@" | sort -u
}

# License-like files in a directory's root, in a fixed order.
license_files() {
  find "$1" -maxdepth 1 -type f \
    \( -iname 'LICEN[CS]E*' -o -iname 'COPYING*' -o -iname 'NOTICE*' -o -iname 'PATENTS*' \) \
    | LC_ALL=C sort
}

# Go's LICENSE and PATENTS. Homebrew's Go keeps LICENSE beside GOROOT, not in it.
go_files() {
  local root f
  root="$(go env GOROOT)"
  for f in LICENSE PATENTS; do
    if [ -f "$root/$f" ]; then echo "$root/$f"
    elif [ -f "$root/../$f" ]; then echo "$root/../$f"
    else echo "no $f in or beside $root" >&2; exit 1
    fi
  done
}

# section TITLE FILES prints a heading and each file's text.
section() {
  local title="$1" files="$2" f
  [ -n "$files" ] || { echo "no license file for $title" >&2; exit 1; }
  printf '\n%s\n%s\n' "================================================================================" "$title"
  while IFS= read -r f; do
    printf '\n--- %s ---\n\n' "${f##*/}"
    cat "$f"
  done <<<"$files"
}

generate() {
  cat <<'EOF'
Third-party notices for jotaside

jotaside binaries include the Go standard library and the Go modules below.
Their license texts follow. jotaside's own license is in LICENSE.

Generated by scripts/third-party-notices.sh; don't edit by hand.
EOF
  local files m dir
  files="$(go_files)"
  section "Go standard library and runtime (https://go.dev)" "$files"
  while IFS= read -r m; do
    dir="$(go mod download -json "$m" | sed -n 's/^[[:space:]]*"Dir": "\(.*\)",$/\1/p')"
    section "$m" "$(license_files "$dir")"
  done < <(modules)
}

if [ "${1:-}" = --check ]; then
  NEW="$(mktemp)"; trap 'rm -f "$NEW"' EXIT
  generate >"$NEW"
  if ! diff -u "$OUT" "$NEW"; then
    echo "$OUT is out of date: run scripts/third-party-notices.sh and commit the result" >&2
    exit 1
  fi
  echo "$OUT is up to date"
else
  generate >"$OUT"
  echo "wrote $OUT"
fi
